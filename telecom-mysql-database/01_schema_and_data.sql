CREATE DATABASE IF NOT EXISTS `telecom`;
USE `telecom`;

DROP TABLE IF EXISTS
bill,
call_record,
data_usage,
sms_record,
subscription,
phone_number,
support_ticket,
customer,
plan;

CREATE TABLE IF NOT EXISTS customer (
customer_id INT NOT NULL AUTO_INCREMENT,
full_name VARCHAR(100) NOT NULL,
email VARCHAR(100),
address VARCHAR(300),
registration_date DATETIME NOT NULL,
PRIMARY KEY (customer_id)
);

CREATE TABLE IF NOT EXISTS phone_number (
phone_id INT NOT NULL AUTO_INCREMENT,
customer_id INT NOT NULL,
number VARCHAR(15) NOT NULL UNIQUE,
status ENUM('active', 'suspended', 'ported') NOT NULL DEFAULT 'active',
date_registered DATETIME NOT NULL,
PRIMARY KEY (phone_id),
FOREIGN KEY (customer_id) REFERENCES customer(customer_id)
);

CREATE TABLE IF NOT EXISTS plan (
plan_id INT NOT NULL AUTO_INCREMENT,
plan_name VARCHAR(100) NOT NULL,
plan_type ENUM('prepaid', 'postpaid') NOT NULL,
monthly_fee DECIMAL(10, 2) NOT NULL,
data_limit INT NOT NULL,
voice_limit INT NOT NULL,
sms_limit INT NOT NULL,
PRIMARY KEY (plan_id)
);

CREATE TABLE IF NOT EXISTS subscription (
subscription_id INT NOT NULL AUTO_INCREMENT,
phone_id INT NOT NULL,
plan_id INT NOT NULL,
activation_date DATETIME NOT NULL,
status ENUM('active', 'suspended', 'cancelled') NOT NULL DEFAULT 'active',
PRIMARY KEY (subscription_id),
FOREIGN KEY (phone_id) REFERENCES phone_number(phone_id),
FOREIGN KEY (plan_id) REFERENCES plan(plan_id)
);

CREATE TABLE IF NOT EXISTS call_record (
call_id INT NOT NULL AUTO_INCREMENT,
subscription_id INT NOT NULL,
call_start DATETIME NOT NULL,
duration INT NOT NULL,
call_recipient VARCHAR(15) NOT NULL,
call_type ENUM('incoming', 'outgoing') NOT NULL,
PRIMARY KEY (call_id),
FOREIGN KEY (subscription_id) REFERENCES subscription(subscription_id)
);

CREATE TABLE IF NOT EXISTS sms_record (
sms_id INT NOT NULL AUTO_INCREMENT,
subscription_id INT NOT NULL,
timestamp DATETIME NOT NULL,
recipient_number VARCHAR(15) NOT NULL,
message_type ENUM('chat', 'Plan Alert', 'OTP') NOT NULL,
direction ENUM('Sent', 'Recieved') NOT NULL,
PRIMARY KEY (sms_id),
FOREIGN KEY (subscription_id) REFERENCES subscription(subscription_id)
);

CREATE TABLE IF NOT EXISTS data_usage (
session_id INT NOT NULL AUTO_INCREMENT,
subscription_id INT NOT NULL,
session_start DATETIME NOT NULL,
session_end DATETIME NOT NULL,
mb_used DECIMAL(10,2),
PRIMARY KEY (session_id),
FOREIGN KEY (subscription_id) REFERENCES subscription(subscription_id)
);

CREATE TABLE IF NOT EXISTS bill (
bill_id INT NOT NULL AUTO_INCREMENT,
subscription_id INT NOT NULL,
billing_month VARCHAR(45) NOT NULL,
total_amount DECIMAL(10,2) NOT NULL,
status ENUM('paid', 'unpaid', 'overdue') DEFAULT 'unpaid',
generated_date DATETIME NOT NULL,
PRIMARY KEY (bill_id),
FOREIGN KEY (subscription_id) REFERENCES subscription(subscription_id)
);

CREATE TABLE IF NOT EXISTS support_ticket (
ticket_id INT NOT NULL AUTO_INCREMENT,
customer_id INT,
issue_type VARCHAR(100) NOT NULL,
description TEXT,
opened_date DATETIME NOT NULL,
status ENUM ('open', 'in progress', 'resolved') DEFAULT 'open',
PRIMARY KEY (ticket_id),
FOREIGN KEY (customer_id) REFERENCES customer(customer_id)
);

